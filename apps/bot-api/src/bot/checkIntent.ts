/**
 * Режим «можно?»: человек не ведёт дневник, а спрашивает про конкретную еду.
 *
 * Отличаем вопрос от записи по тексту сообщения (подписи к фото или самого
 * текста). Никаких вызовов модели: правило должно срабатывать мгновенно и
 * одинаково, иначе пользователь не поймёт, почему одно и то же фото то
 * записалось, то нет.
 *
 * `strong` — явные слова-вопросы («можно», «проверь»). Одного знака «?» мало,
 * когда рядом есть недавняя запись: «там точно 300 грамм?» — это уточнение
 * прошлого приёма, а не новая проверка. Решение остаётся за вызывающим.
 */

const STRONG_WORDS =
  /(^|[^а-яё])(можно|нельзя|провер(ь|ить|ка)|подходит|подойд[её]т|вписывается|стоит ли|разреш(ено|ается)|допустимо|как насч[её]т|а если)([^а-яё]|$)/i;

export interface CheckIntent {
  /** Сообщение — вопрос о еде, а не запись. */
  check: boolean;
  /** Есть явное слово-вопрос, а не только знак «?». */
  strong: boolean;
  /** Что остаётся от текста после вопросительных слов: подсказка модели о блюде или null. */
  hint: string | null;
}

export function detectCheckIntent(text: string | undefined | null): CheckIntent {
  const raw = (text ?? "").trim();
  if (!raw) return { check: false, strong: false, hint: null };

  const strong = STRONG_WORDS.test(raw);
  const question = raw.includes("?");
  if (!strong && !question) return { check: false, strong: false, hint: null };

  // Подсказка модели: убираем служебные слова и обращения, оставляем блюдо.
  const hint = raw
    .replace(/[?!]+/g, " ")
    .replace(STRONG_WORDS, " ")
    .replace(/(^|[^а-яё])(мне|это|такое|вот|а|ли|же|его|её|их|есть|съесть|скажи|подскажи|ну|и)(?=[^а-яё]|$)/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

  return { check: true, strong, hint: hint.length >= 3 ? hint : null };
}
