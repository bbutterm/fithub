const BY_ID = new Map(DIET_PRESETS.map((d) => [d.id, d]));

export function getDietPreset(id: string): DietPreset | undefined {
  return BY_ID.get(id as DietPresetId);
}

/** Отсеивает неизвестные идентификаторы и дубли, сохраняя порядок справочника. */
export function normalizeDiets(ids: readonly string[]): DietPresetId[] {
  const set = new Set(ids);
  return DIET_PRESETS.filter((d) => set.has(d.id)).map((d) => d.id);
}

export type DietContext = {
  /** Подписи включённых режимов — для показа человеку. */
  labels: string[];
  /** Правила всех включённых режимов плюс произвольные ограничения — для промпта. */
  rulesText: string;
};

/**
 * Собирает контекст диеты. Возвращает null, если пользователь ничего не задал —
 * это сигнал вызывающему коду пропустить проверку и не тратить вызов модели.
 */
export function buildDietContext(params: {
  diets: readonly string[];
  notes?: string | null;
  allergies?: readonly string[];
}): DietContext | null {
  const presets = normalizeDiets(params.diets).map((id) => BY_ID.get(id)!);
  const notes = params.notes?.trim();
  const allergies = params.allergies?.filter((a) => a.trim()) ?? [];
  if (presets.length === 0 && !notes && allergies.length === 0) return null;

  const blocks = presets.map((p) => `Режим «${p.label}» (${p.hint}):\n${p.rules}`);
  if (allergies.length > 0) {
    // Аллергия строже любой диеты: это не «нежелательно», а «нельзя».
    blocks.push(`Аллергии и непереносимости (строгий запрет): ${allergies.join(", ")}.`);
  }
  if (notes) blocks.push(`Дополнительные ограничения от пользователя: ${notes}`);

  const labels = presets.map((p) => p.label);
  if (labels.length === 0) labels.push("ваши ограничения");

  return { labels, rulesText: blocks.join("\n\n") };
}
