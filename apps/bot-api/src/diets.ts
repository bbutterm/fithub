//
// Ключевая идея: модели передаётся не название диеты, а её ПРАВИЛА текстом.
// Если спросить «подходит ли это для стола №5», модель ответит по памяти —
// каждый раз немного по-разному. Правила в коде делают ответ предсказуемым,
// и их можно поправить, не трогая промпт.
//
// Это справочник питания, а не медицинские назначения: диету выбирает
// пользователь (обычно со слов врача), бот только сверяет с ней еду.

