/**
 * Текст от модели → HTML для Telegram.
 *
 * Модель просят писать без разметки, но она всё равно иногда выделяет заголовки
 * звёздочками. Без parse_mode они уходят пользователю как есть — «**Динамика**».
 * Здесь звёздочки превращаются в <b>, а всё остальное экранируется: иначе
 * случайный «<» в тексте заставит Telegram отклонить сообщение целиком.
 */
export function toTelegramHtml(text: string): string {
  const escaped = text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return (
    escaped
      // **жирный** — только парные, непарная звёздочка остаётся звёздочкой
      .replace(/\*\*(.+?)\*\*/g, "<b>$1</b>")
      // заголовки «### Раздел» — просто жирная строка
      .replace(/^#{1,6}\s+(.+)$/gm, "<b>$1</b>")
  );
}
