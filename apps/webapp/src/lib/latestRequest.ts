/**
 * «Побеждает последний запрос»: ответ на отменённый или устаревший запрос
 * игнорируется.
 *
 * Нужно там, где человек быстро переключает выбор: ответы приходят в том
 * порядке, в каком ответил сервер, а не в каком их спрашивали, и без этого на
 * экране оказывался результат по предыдущему нажатию. Счётчик вместо
 * AbortController: отменять сам запрос не нужно, достаточно не показывать его
 * ответ, а разбираться с прерванными промисами в каждом обработчике дороже.
 */
export interface LatestRequest {
  /** Начать новый запрос. Возвращает проверку «мой ответ ещё нужен?». */
  begin(): () => boolean;
  /** Забыть всё, что сейчас в полёте: ни один ответ больше не примут. */
  cancel(): void;
}

export function createLatestRequest(): LatestRequest {
  let current = 0;
  return {
    begin() {
      const id = ++current;
      return () => id === current;
    },
    cancel() {
      current++;
    }
  };
}
